"""Causal, capacity-conserving surrogate execution for Stage18 snapshots.

Not a physical vLLM simulator. The execution clock and resource accounting are exact
for the declared surrogate. Service curves, scheduler-boundary alignment and cache
retention are still modeling assumptions. No network, GPU or control-file access.

Important differences from v1:
* batch completion events are committed globally before any same-time batch starts;
* successors never move another replica's clock;
* no optimistic independent-request terminal approximation is allowed;
* current cap/order expires at a physical-time boundary; a common continuation follows;
* incomplete CPU evaluations have cost=None and cannot win a search;
* completed simulated prefixes enter a labeled cache model, not native certificates.
"""
from __future__ import annotations

import copy
import heapq
import math
import time
from collections import Counter, defaultdict
from dataclasses import dataclass
from typing import Any, Callable

from .service import coefficients as service_coefficients

EPS = 1e-8


def settings(cfg: dict) -> dict:
    out = dict(cfg)
    out.setdefault('replicas', 4)
    out.setdefault('hard_total', 4096)
    out.setdefault('max_num_seqs', 64)
    out.setdefault('block_size', 16)
    out.setdefault('base_cap', 1024)
    out.setdefault('caps', [256, 512, 1024, 2048, 4096])
    out.setdefault('epoch_s', .2)
    out.setdefault('action_horizon_ms', 1000 * out['epoch_s'])
    out.setdefault('apply_delay_ms', 0.)
    # Zero means immediate common continuation admission on readiness. Positive
    # values mean an absolute periodic common admission clock (not v1 end+period).
    out.setdefault('continuation_period_ms', 1000 * out['epoch_s'])
    out.setdefault('max_surrogate_events', 50000)
    out.setdefault('max_surrogate_ms', 600000.)
    out.setdefault('admission_reserve_fraction', .9)
    out.setdefault('cache_scenario', 'no_unverified_reuse')
    out.setdefault('age_limit_s', 5.)
    return out


@dataclass
class CacheEntry:
    tokens: int
    status: str
    origin: str
    last_touch: float
    valid_until: float | None = None


class CacheModel:
    """Small conservative cache scenario model, NEVER a native residency proof.

    New work becomes reusable only after its producing batch completes. Two cold
    siblings in the same batch cannot reuse one another's unfinished work.
    Initial history can be ignored or considered retained in a separate sensitivity
    scenario. Absence of a certificate is counted as unknown, not claimed cold.
    """
    def __init__(self, snapshot: dict, cfg: dict):
        self.block = cfg['block_size']
        self.capacity = snapshot.get('capacity_blocks', [4096] * snapshot['replicas'])
        self.scenario = cfg.get('cache_scenario', 'no_unverified_reuse')
        if self.scenario not in ('no_unverified_reuse', 'history_if_retained'):
            raise ValueError('unknown cache scenario')
        self.entries: dict[tuple[int, str], CacheEntry] = {}
        self.known = {}  # observed/model-known absence is not unknown
        self.counts: Counter = Counter()
        for h, rs in snapshot.get('prefix_certificates', {}).items():
            for r, length in rs.items():
                r = int(r)
                if not 0 <= r < snapshot['replicas'] or int(length) < 0:
                    raise ValueError('invalid prefix certificate')
                length = int(length) // self.block * self.block
                if length:
                    self.entries[r, h] = CacheEntry(length, 'observed_active', 'snapshot_certificate', 0.)
                    self.known[r,h]='snapshot_certificate'
        # Optional stronger source format, not generated by the old snapshot exporter.
        for e in snapshot.get('cache_evidence', []):
            r, h = int(e['replica']), str(e['prefix_hash'])
            expiry = e.get('valid_until_ms')
            if not 0 <= r < snapshot['replicas']:
                raise ValueError('cache evidence replica')
            if e['state'] in ('evicted','absent','resident_uncomputed') and e.get('known',True):
                self.entries.pop((r,h),None);self.known[r,h]=e['state']
                self.counts['observed_unavailable_records']+=1
                continue
            if e['state'] not in ('active_computed', 'reclaimable_computed'):
                self.counts['unknown_evidence_records'] += 1
                continue
            if expiry is not None and float(expiry) < 0:
                continue
            self.known[r,h]=e['state']
            self.entries[r, h] = CacheEntry(
                int(e['tokens']) // self.block * self.block,
                e['state'], 'snapshot_resident_evidence', 0.,
                None if expiry is None else float(expiry))
        if self.scenario == 'history_if_retained':
            maxshare = {}
            for n in snapshot['nodes'].values():
                if n.get('prefix_hash'):
                    h = n['prefix_hash']
                    maxshare[h] = max(maxshare.get(h, 0), int(n.get('share', 0)))
            for h, replicas in snapshot.get('prefix_history', {}).items():
                for r in replicas:
                    if (r, h) not in self.entries and (r,h) not in self.known and maxshare.get(h, 0):
                        self.entries[r, h] = CacheEntry(maxshare[h] // self.block * self.block,
                                                      'unverified_retention', 'history_scenario_only', 0.)
                        self.counts['history_assumptions'] += 1

    def length(self, r: int, h: str | None, at: float) -> int:
        if not h:
            return 0
        e = self.entries.get((r, h))
        if e is None:
            return 0
        if e.valid_until is not None and at > e.valid_until + EPS:
            self.entries.pop((r,h),None);self.known.pop((r,h),None)
            self.counts['evidence_expired'] += 1
            return 0
        return e.tokens

    def credit(self, r: int, n: dict, take: int, at: float) -> int:
        h = n.get('prefix_hash')
        if not h or not n.get('share', 0):
            return 0
        length = min(self.length(r, h, at), int(n['share']))
        if not length:
            self.counts['known_unavailable_prefix_lookups' if (r,h) in self.known else 'unknown_prefix_lookups'] += 1
            return 0
        e = self.entries[r, h]
        e.last_touch = at
        credit = min(take, max(0, length - min(n['prompt'], n.get('computed', 0))))
        if credit:
            self.counts['credited_lookups'] += 1
            self.counts['logical_overlap_tokens'] += credit
            self.counts['credit_from_' + e.origin] += 1
        return credit

    def produced(self, r: int, n: dict, at: float) -> None:
        h = n.get('prefix_hash')
        length = min(int(n.get('share', 0)), int(n.get('computed', 0)), int(n['prompt']))
        length = length // self.block * self.block
        if not h or not length:
            return
        self.known[r,h]='surrogate_batch_completion'
        before = self.entries.get((r, h))
        if before is None or length > before.tokens:
            self.entries[r, h] = CacheEntry(length, 'modeled_computed', 'surrogate_batch_completion', at)
            self.counts['modeled_prefix_updates'] += 1
        else:
            before.last_touch = at

    def evict_for_reservations(self, r: int, active: list[dict], at: float) -> None:
        # Conservatively reserve private+shared in-flight work without deducting
        # estimated cache savings. This is NOT a reproduction of native APC LRU.
        reserve = sum(math.ceil((n['prompt'] + n['output']) / self.block) for n in active)
        allowance = max(0, int(self.capacity[r]) - reserve)
        pinned = {n.get('prefix_hash') for n in active if n.get('computed', 0) > 0}
        inactive = [(k, e) for k, e in self.entries.items() if k[0] == r and k[1] not in pinned]
        used = sum(math.ceil(e.tokens / self.block) for _, e in inactive)
        for key, entry in sorted(inactive, key=lambda kv: (kv[1].last_touch, kv[0][1])):
            if used <= allowance:
                break
            self.entries.pop(key,None);self.known[key]='modeled_evicted'
            used -= math.ceil(entry.tokens / self.block)
            self.counts['modeled_conservative_evictions'] += 1


def _predict(model, r, p, d, dc, pc, cache):
    from .service import predict
    return predict(model,r,p,d,dc,pc,cache)


def _validate(s: dict, a: dict, cfg: dict):
    R = s['replicas']
    if R < 1 or set(a['placement']) != set(s['ready']):
        raise ValueError('placement must cover exactly the observed ready set')
    if len(a['caps']) != R or any(type(c) is not int or c not in cfg['caps'] for c in a['caps']):
        raise ValueError('caps outside the declared envelope')
    if not 0 <= cfg['apply_delay_ms'] < cfg['action_horizon_ms']:
        raise ValueError('current action must apply before its absolute validity boundary')
    if cfg['hard_total'] < cfg['max_num_seqs'] or cfg['block_size'] <= 0:
        raise ValueError('invalid common envelope')
    if len(a['order']) != len(set(a['order'])) or any(k not in s['nodes'] for k in a['order']):
        raise ValueError('invalid priority order')
    if len(a['admit']) != len(set(a['admit'])) or not set(a['admit']) <= set(s['ready']):
        raise ValueError('invalid admission set')
    for k, n in s['nodes'].items():
        if n['state'] not in ('done', 'blocked', 'ready', 'submitted'):
            raise ValueError('unsupported node state')
        if any(p not in s['nodes'] for p in n['parents']):
            raise ValueError('snapshot is missing a known DAG parent')
        if n['prompt'] < 1 or n['output'] < 1 or n.get('output_done', 0) < 0:
            raise ValueError('invalid token work')
        if n['state'] == 'submitted' and not all(s['nodes'][p]['state'] == 'done' for p in n['parents']):
            raise ValueError('submitted request has unfinished parents')
        if n['state'] == 'submitted' and (type(n.get('replica')) is not int or not 0 <= n['replica'] < R):
            raise ValueError('submitted request needs immutable replica')
    for k, r in a['placement'].items():
        if s['nodes'][k]['state'] != 'ready' or type(r) is not int or not 0 <= r < R:
            raise ValueError('invalid ready-node placement')
        if not all(s['nodes'][p]['state'] == 'done' for p in s['nodes'][k]['parents']):
            raise ValueError('dependency before admission')
    # Explicit DAG validation. Cycles never become artificial infinite service times.
    color = {}
    def visit(k):
        if color.get(k) == 1:
            raise ValueError('DAG cycle')
        if color.get(k) == 2:
            return
        color[k] = 1
        for p in s['nodes'][k]['parents']:
            visit(p)
        color[k] = 2
    for k in s['nodes']:
        visit(k)


def evaluate(snapshot: dict, action: dict, model: dict, config: dict, *,
             deadline: float | None = None, record_events: bool = False,
             time_fn: Callable[[], float] = time.monotonic) -> dict[str, Any]:
    """Evaluate one complete current action plus common reference continuation.

    `deadline` is an absolute CPU monotonic deadline shared by the entire caller's
    search. No deadline extension, partial scalar score or hidden event-horizon shrink.
    A missing deadline means CPU-only full surrogate completion, not online viability.
    """
    cpu_start = time_fn()
    cfg = settings(config)
    _validate(snapshot, action, cfg)
    ns = {k: dict(n) for k,n in snapshot['nodes'].items()} # nested parents are read-only
    coeff = [{q:service_coefficients(model,r,q) for q in ('prefill_only','decode_only','mixed')} for r in range(snapshot['replicas'])]
    R = snapshot['replicas']
    horizon = float(cfg['action_horizon_ms'])
    apply_at = float(cfg['apply_delay_ms'])
    period = float(cfg['continuation_period_ms'])
    if period < 0:
        raise ValueError('negative continuation period')
    ledger = CacheModel(snapshot, cfg)
    history = {k: set(v) for k, v in snapshot.get('prefix_history', {}).items()}
    native_rank = {k: i for r, ks in snapshot.get('queue_order', {}).items() for i, k in enumerate(ks)}
    rank = {k: i for i, k in enumerate(action['order'])}
    succ = defaultdict(list)
    for k, n in ns.items():
        for p in n['parents']:
            succ[p].append(k)
    node_done = {k: 0. for k, n in ns.items() if n['state'] == 'done'}
    groups = defaultdict(set)
    for k, n in ns.items():
        groups[n['wid']].add(k)
    pending_wf = {w for w, ks in groups.items() if not all(k in node_done for k in ks)}
    wf_done = {w: 0. for w in groups if w not in pending_wf}
    unfinished_counts={w:sum(k not in node_done for k in ks) for w,ks in groups.items()}
    finished_workflow_events=set()
    ready_due = {}
    ready_time = {}
    original_ready = set(snapshot['ready'])
    for k in original_ready:
        ready_time[k] = 0.
        ready_due[k] = horizon  # NOT automatically admitted if it failed a resource gate.
        ns[k]['replica'] = None  # placement of a deferred, unsubmitted request is not a commitment.
    nextseq = 0
    heap = []
    def push(t, kind, payload):
        nonlocal nextseq
        nextseq += 1
        heapq.heappush(heap, (float(t), nextseq, kind, payload))
    push(0., 'initialize', None)  # existing in-flight work advances during control delay
    push(apply_at, 'apply', None)
    push(horizon, 'expire', None)
    for e in snapshot.get('future_cache_events', []):
        # Explicit synthetic/adapter events only; never invented from route history.
        if e['at_ms'] >= 0:
            push(float(e['at_ms']), 'cache_event', copy.deepcopy(e))
    busy = [None] * R
    last_finish = [0.] * R
    current_caps = list(snapshot.get('current_caps', [cfg['base_cap']] * R))
    now = 0.
    prev = 0.
    area = 0.
    area_h = 0.
    batch_starts = 0
    batch_completions = 0
    expanded_iterations = 0
    coalesced_decode_batches = 0
    trace = []
    seen_admits = []
    active_window = False
    expired = False
    reason = None
    max_p = 0
    max_total = 0
    lastwake = None

    def check_cpu():
        return deadline is not None and time_fn() >= deadline

    active_keys=[set(k for k,n in ns.items() if n['state']=='submitted' and n.get('replica')==r) for r in range(R)]
    dirty=[True]*R
    started_keys={k for k,n in ns.items() if n['state']=='submitted' and (n.get('computed',0)>0 or n.get('phase')=='decode')}
    blocked=set(k for k,n in ns.items() if n['state']=='blocked')
    release_candidates=set(k for k in blocked if all(p in node_done for p in ns[k]['parents']))
    partitions=[None]*R
    def active_at(r):
        return [ns[k] for k in active_keys[r]]

    def capacity_ok(k, r):
        active = active_at(r)
        blocks = sum(math.ceil((n['prompt'] + n['output']) / cfg['block_size']) for n in active)
        need = math.ceil((ns[k]['prompt'] + ns[k]['output']) / cfg['block_size'])
        limit = int(snapshot.get('capacity_blocks', [4096] * R)[r] * cfg['admission_reserve_fraction'])
        return len(active) < cfg['max_num_seqs'] and blocks + need <= limit

    def admit(k, r, at, kind):
        if ns[k]['state'] != 'ready':
            raise ValueError('double surrogate dispatch')
        if not all(p in node_done for p in ns[k]['parents']):
            raise ValueError('surrogate dependency violation')
        if not capacity_ok(k, r):
            return False
        ns[k]['replica'] = r
        ns[k]['state'] = 'submitted'
        active_keys[r].add(k);dirty[r]=True;partitions[r]=None
        ns[k]['phase'] = 'prefill'
        ns[k]['computed'] = 0
        ns[k]['output_done'] = 0
        native_rank[k] = 10**6 + len(seen_admits)
        ready_due.pop(k, None)
        seen_admits.append({'node': k, 'replica': r, 'at_ms': at, 'kind': kind})
        return True

    def next_tick(t):
        if period == 0:
            return t
        # Return current tick when exactly aligned; otherwise the next absolute tick.
        return max(horizon, math.ceil((t - horizon - EPS) / period) * period + horizon)

    def release_successors(at):
        for k in list(release_candidates):
            release_candidates.discard(k)
            if k not in blocked:continue
            n=ns[k]
            if all(p in node_done for p in n['parents']):
                blocked.remove(k)
                n['state'] = 'ready'
                n['replica'] = None
                ready_time[k] = at
                n['ready_at'] = snapshot['now'] + at / 1000
                ready_due[k] = next_tick(at) if period else at
                # Never modify last_finish or busy state of ANY replica here.

    def common_admit(at):
        nonlocal lastwake
        ready = [k for k, t in ready_due.items() if t <= at + EPS and ns[k]['state'] == 'ready']
        for k in sorted(ready, key=lambda x: (ready_time.get(x, 0.), x)):
            n = ns[k]
            lengths=[ledger.length(r,n.get('prefix_hash'),at) for r in range(R)]
            maximum=max(lengths,default=0)
            h=n.get('prefix_hash')
            if maximum:pref={r for r,v in enumerate(lengths) if v==maximum}
            elif h and all((r,h) in ledger.known for r in range(R)):pref=set(range(R))
            else:pref=history.get(h,set())
            options=sorted(pref) if pref else list(range(R))
            def loadkey(r):
                # Same reference rule: native running + twice waiting; no extra
                # shortest-work tie breaker or capacity-driven rerouting in the model.
                active=active_keys[r];waiting=sum(k not in started_keys for k in active)
                return (len(active)+waiting,r)
            target=min(options,key=loadkey)
            if not capacity_ok(k,target):
                ready_due[k]=at+period if period else at
                continue
            admit(k,target,at,'common_continuation')
        if period and ready_due:
            t = min(ready_due.values())
            if t <= at + EPS:
                t = at + period
            if lastwake is None or abs(t - lastwake) > EPS:
                push(t, 'wake', None)
                lastwake = t

    def schedule(r, at):
        nonlocal batch_starts, max_p, max_total
        if busy[r] is not None:
            return
        active = list(active_keys[r])
        if not active:
            return
        # Declared running/decode, partial-prefill, new-prefill boundaries.
        if partitions[r] is None:
            dec = sorted([k for k in active if ns[k].get('phase') == 'decode'],
                         key=lambda k: (native_rank.get(k, 10**9), k))[:cfg['max_num_seqs']]
            part = [k for k in active if ns[k].get('phase') != 'decode' and ns[k].get('computed', 0) > 0]
            waiting = [k for k in active if ns[k].get('phase') != 'decode' and ns[k].get('computed', 0) <= 0]
            partitions[r]=(dec,part,waiting)
        else:dec,part,waiting=partitions[r]
        def ordered(ks):
            use_priority = active_window and not any(
                at / 1000 + snapshot['now'] -
                (ns[k]['accepted_at'] if ns[k].get('accepted_at') is not None else
                 ns[k]['ready_at'] if ns[k].get('ready_at') is not None else snapshot['now'])
                >= cfg['age_limit_s'] for k in ks)
            if use_priority:
                return sorted(ks, key=lambda k: (rank.get(k,len(rank)),native_rank.get(k,10**9),k))
            # Expiration restores the same acceptance FIFO used by the native hook.
            return sorted(ks,key=lambda k: (ns[k].get('accepted_at') if ns[k].get('accepted_at') is not None else
                           ns[k].get('ready_at') if ns[k].get('ready_at') is not None else snapshot['now'],
                           native_rank.get(k,10**9),k))
        left = cfg['hard_total'] - len(dec)
        cap = current_caps[r]
        allowed = min(left, cap)
        chosen = []
        cache = 0
        context = 0
        if dirty[r]:
            ledger.evict_for_reservations(r, active_at(r), at);dirty[r]=False
        for k in ordered(part) + ordered(waiting):
            if allowed <= 0 or len(dec) + len(chosen) >= cfg['max_num_seqs']:
                break
            n = ns[k]
            remaining = max(0, int(n['prompt']) - int(n.get('computed', 0)))
            if remaining == 0:
                # An inconsistent snapshot must not create a free output token.
                raise ValueError('prefill state with no uncomputed prompt; provide boundary-consistent snapshot')
            take = min(allowed, remaining)
            if take < remaining:
                take = take // cfg['block_size'] * cfg['block_size']
            if take == 0:
                break
            chosen.append((k, take))
            cache += min(max(0,take-1), ledger.credit(r, n, take, at)) # native full-hit recomputes last query token
            context = max(context, int(n.get('computed', 0)))
            allowed -= take
        p = sum(t for _, t in chosen)
        d = len(dec)
        if not p + d:
            return
        assert p <= cap and p + d <= cfg['hard_total']
        assert len(chosen) + d <= cfg['max_num_seqs']
        dc = sum(ns[k]['prompt'] + ns[k].get('output_done', 0) for k in dec)
        eff=max(0,p-cache);c=coeff[r]['mixed' if p and d else 'prefill_only' if p else 'decode_only']
        dt=max(.1,c[0]+c[1]*eff/1024.+c[2]*d/16.+c[3]*dc/65536.+c[4]*eff*context/4194304.+c[5]*eff*d/16384.)
        decode_steps=1
        # Exact within this nonnegative linear HOST model: while membership is
        # unchanged, decode context grows by d each step, so step duration is an
        # arithmetic progression. Never cross the next known global event, an
        # output completion, an admission/expiry event or a prefill opportunity.
        # record_events=True retains the original one-batch-at-a-time trace.
        if p==0 and d>0 and not part and not waiting and not record_events and cfg.get('coalesce_decode',True):
            raw=c[0]+c[2]*d/16.+c[3]*dc/65536.
            slope=c[3]*d/65536.
            bound=min(ns[k]['output']-ns[k].get('output_done',0) for k in dec)
            if raw>=.1-EPS or slope==0:
                until=heap[0][0]-at if heap else float('inf')
                def duration(k):return k*dt+slope*k*(k-1)/2
                lo,hi=1,max(1,int(bound))
                while lo<hi:
                    mid=(lo+hi+1)//2
                    if duration(mid)<=until+EPS:lo=mid
                    else:hi=mid-1
                decode_steps=lo
                dt=duration(lo)
        b = {'replica': r, 'start_ms': at, 'end_ms': at + dt,
             'prefill': chosen, 'decode': dec, 'prefill_tokens': p,
             'decode_tokens': d, 'cache_overlap_proxy': cache, 'cap': cap,
             'current_action_window': active_window, 'decode_steps': decode_steps}
        busy[r] = b
        started_keys.update(dec+[k for k,_ in chosen])
        push(at + dt, 'complete', b)
        if record_events:
            trace.append(copy.deepcopy(b))
        batch_starts += 1
        max_p = max(max_p, p)
        max_total = max(max_total, p + d)

    for initial in snapshot.get('inflight_batches', []):
        r=int(initial['replica'])
        if busy[r] is not None:raise ValueError('duplicate native inflight replica')
        pre=[(k,int(t)) for k,t in initial.get('prefill',[]) if k in ns and ns[k]['state']=='submitted']
        dec=[k for k in initial.get('decode',[]) if k in ns and ns[k]['state']=='submitted']
        if not pre and not dec:continue
        b={'replica':r,'start_ms':-float(initial.get('elapsed_ms',0)),
           'end_ms':max(.001,float(initial['remaining_ms'])),'prefill':pre,'decode':dec,
           'prefill_tokens':sum(t for _,t in pre),'decode_tokens':len(dec),
           'cache_overlap_proxy':initial.get('cache_overlap_proxy',0),'cap':initial.get('cap',cfg['base_cap']),
           'current_action_window':False,'native_inflight_observation':True}
        busy[r]=b;started_keys.update(dec+[k for k,_ in pre]);push(b['end_ms'],'complete',b)
        if record_events:trace.append(copy.deepcopy(b))

    # Admit any snapshot-blocked nodes whose parents are already done. In a correctly
    # recorded snapshot they normally appear in ready. Late discovery is not hidden.
    release_successors(0.)
    while pending_wf:
        if check_cpu():
            reason = 'cpu_deadline'
            break
        if batch_completions >= cfg['max_surrogate_events']:
            reason = 'event_safety_limit'
            break
        if not heap:
            common_admit(now)
            for r in range(R):
                schedule(r, now)
            if not heap:
                reason = 'no_feasible_progress'
                break
        now = heap[0][0]
        if now > cfg['max_surrogate_ms']:
            reason = 'virtual_time_safety_limit'
            break
        area += len(pending_wf) * max(0, now - prev)
        area_h += len(pending_wf) * max(0, min(now, horizon) - min(prev, horizon))
        prev = now
        at_events = []
        while heap and abs(heap[0][0] - now) <= EPS:
            at_events.append(heapq.heappop(heap))
        # ALL completions at a timestamp precede all releases and dispatches.
        for _, _, kind, b in at_events:
            if kind != 'complete':
                continue
            r = b['replica']
            if busy[r] is not b:
                raise RuntimeError('surrogate replica overlap')
            for k in b['decode']:
                ns[k]['output_done'] += b.get('decode_steps',1)
            if b['prefill']:partitions[r]=None
            for k, take in b['prefill']:
                n = ns[k]
                n['computed'] += take
                if n['computed'] >= n['prompt']:
                    n['phase'] = 'decode'
                    n['output_done'] = max(1, n.get('output_done', 0))
                ledger.produced(r, n, now)
            for k in b['decode'] + [k for k, _ in b['prefill']]:
                n = ns[k]
                if n['output_done'] >= n['output']:
                    n['state'] = 'done'
                    active_keys[r].discard(k);dirty[r]=True;partitions[r]=None
                    node_done[k] = now
                    release_candidates.update(succ[k])
                    unfinished_counts[n['wid']]-=1
                    if unfinished_counts[n['wid']]==0:finished_workflow_events.add(n['wid'])
                    if n.get('prefix_hash'):
                        history.setdefault(n['prefix_hash'], set()).add(r)
            busy[r] = None
            last_finish[r] = now
            batch_completions += 1
            expanded_iterations += b.get('decode_steps',1)
            if b.get('decode_steps',1)>1:coalesced_decode_batches+=1
        for w in finished_workflow_events:
            wf_done[w] = max(node_done[k] for k in groups[w])
            pending_wf.remove(w)
        finished_workflow_events.clear()
        release_successors(now)
        for _, _, kind, payload in at_events:
            if kind == 'cache_event':
                if payload['state'] == 'evicted':
                    key=(int(payload['replica']),payload['prefix_hash'])
                    ledger.entries.pop(key,None);ledger.known[key]='explicit_evicted'
                    ledger.counts['explicit_evictions'] += 1
                else:
                    raise ValueError('unsupported explicit cache event')
            elif kind == 'apply':
                active_window = True
                current_caps = list(action['caps'])
                for k in action['admit']:
                    if not admit(k, action['placement'][k], now, 'current_action'):
                        # Invalid complete candidates are rejected, not silently improved.
                        reason = 'candidate_admission_exceeds_common_resources'
                        break
            elif kind == 'expire':
                expired = True
                active_window = False
                current_caps = [cfg['base_cap']] * R
                for k in original_ready:
                    if ns[k]['state'] == 'ready':
                        ready_due[k] = now
            elif kind == 'wake':
                lastwake = None
        if reason:
            break
        common_admit(now)
        for r in range(R):
            if check_cpu():
                reason = 'cpu_deadline'
                break
            schedule(r, now)
        if reason:
            break
    complete = not pending_wf and reason is None
    total = sum(wf_done.values()) if complete else None
    if complete and abs(area - total) > max(.001, abs(total) * 1e-9):
        raise RuntimeError('unfinished-workflow area identity violated')
    return {
        'complete': complete, 'rankable': complete,
        'reason': 'complete_surrogate' if complete else reason,
        'sum_remaining_jct_ms': total,
        'workflow_prediction_ms': wf_done if complete else None,
        'completed_workflows_at_cutoff': wf_done,
        'node_completion_ms': node_done,
        'unfinished_area_to_horizon_ms': area_h,
        'common_continuation_value_ms': (total - area_h) if complete else None,
        'partial_unfinished_area_ms': area,
        'rollout_steps': batch_completions,
        'expanded_model_iterations': expanded_iterations,
        'coalesced_decode_batches': coalesced_decode_batches,
        'terminal_estimate_used': False,
        'physical_horizon_ms': horizon,
        'apply_delay_ms': apply_at,
        'continuation_cap': cfg['base_cap'],
        'continuation_period_ms': period,
        'cache_scenario': cfg['cache_scenario'],
        'cache_counters': dict(ledger.counts),
        'admissions': seen_admits,
        'scheduled_prefill_peak': max_p,
        'scheduled_total_peak': max_total,
        'event_trace': trace if record_events else None,
        'cpu_wall_ms': 1000 * (time_fn() - cpu_start),
        'physical_gpu_time': False,
        'native_cache_residency_proven': False,
        'initial_boundary_assumption': 'native batch membership/progress preserved when supplied; residual service duration is a model estimate',
        'scope': 'corrected causal surrogate only; no counterfactual ground truth or online-runtime release',
    }
